// Release signing is optional. When these environment variables are present (GitHub Actions
// sets them from repository secrets) the release build is signed; otherwise it stays unsigned.
val signingKeystorePath: String? = System.getenv("EQX_KEYSTORE_PATH")
val signingStorePassword: String? = System.getenv("EQX_KEYSTORE_PASSWORD")
val signingKeyAlias: String? = System.getenv("EQX_KEY_ALIAS")
val signingKeyPassword: String? = System.getenv("EQX_KEY_PASSWORD")
val hasReleaseSigning = !signingKeystorePath.isNullOrBlank() &&
    file(signingKeystorePath!!).exists() &&
    !signingStorePassword.isNullOrBlank() &&
    !signingKeyAlias.isNullOrBlank()

